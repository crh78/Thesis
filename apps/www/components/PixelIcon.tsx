export type PixelIconName = keyof typeof GRIDS;

/** One rect per run of same-tone pixels in a row. */
function rects(grid: readonly string[]) {
  const out: { x: number; y: number; w: number; dim: boolean }[] = [];
  grid.forEach((row, y) => {
    for (let x = 0; x < row.length; ) {
      const c = row[x];
      if (c === ".") { x++; continue; }
      let w = 1;
      while (row[x + w] === c) w++;
      out.push({ x, y, w, dim: c === "+" });
      x += w;
    }
  });
  return out;
}

/** The icon in `currentColor`, its second tone at 55%. */
export function PixelIcon({ name, size = 20 }: { name: PixelIconName; size?: number }) {
  return (
    <svg viewBox="0 0 12 12" width={size} height={size} shapeRendering="crispEdges" fill="currentColor" aria-hidden>
      {rects(GRIDS[name]).map((r) => (
        <rect key={`${r.x}-${r.y}`} x={r.x} y={r.y} width={r.w} height={1} fillOpacity={r.dim ? 0.55 : 1} />
      ))}
    </svg>
  );
}
