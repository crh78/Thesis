export type Region = { code: string; name: string };

export function countries(locale?: string): Region[] {
  let names: Intl.DisplayNames | null = null;
  try {
    names = new Intl.DisplayNames(locale ? [locale] : undefined, { type: "region" });
  } catch {
    /* very old browser: codes only */
  }
  return CODES.map((code) => ({ code, name: names?.of(code) ?? code })).sort((a, b) => a.name.localeCompare(b.name));
}

/** The browser's region if it's a real country, else the US (like the app's default). */
export function defaultCountry(): string {
  const langs = typeof navigator === "undefined" ? [] : navigator.languages ?? [navigator.language];
  for (const l of langs) {
    const region = l.split("-").find((p, i) => i > 0 && /^[A-Z]{2}$/.test(p));
    if (region && CODES.includes(region)) return region;
  }
  return "US";
}

